/**
 * Resuelve cualquier texto, emoji o nombre a un glifo DOT oficial.
 */
export function resolveDotGlyph(input?: string): string | null {
  if (!input) return null;
  const trimmed = input.trim().toUpperCase();

  // Coincidencia directa por nombre de clave
  if (DOT_GLYPHS_8X8[trimmed]) return trimmed;

  return MAP[trimmed] ?? MAP[input.trim()] ?? null;
}

